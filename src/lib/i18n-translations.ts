/**
 * Interpolate `{{key}}` placeholders in a translation string with the
 * values from `params`. Used by the programmatic SEO pages and any
 * other string that needs runtime values (city name, country name,
 * counts, etc.).
 *
 * Example:
 *   t('en', 'seo.cities.detailH1', { city: 'Beijing' })
 *   // → "Study in Beijing"
 *
 * Unknown placeholders are left as-is so missing params are visible
 * in the rendered output (better than silently swallowing them).
 */
export function t(
  locale: Locale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const raw = translations[locale]?.[key] ?? translations[DEFAULT_LOCALE]?.[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{\{\s*(\w+)\s*\}\}/g, (match, name: string) => {
    if (Object.prototype.hasOwnProperty.call(params, name)) {
      return String(params[name]);
    }
    return match;
  });
}

export const DEFAULT_LOCALE: Locale = 'en';
